"""Turn results/calibration_free_results.json into RESULTS.md (never edit that file by hand)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).parent
TITLES = {"rome_als": "Rome, 8 people with ALS, row/column (BNCI 2014-008)",
          "rome_healthy": "Rome, 10 healthy people, row/column (BNCI 2014-009)",
          "etsu_als": "ETSU, 11 people with ALS, checkerboard (bigP3BCI Study L)"}


def pct(s: dict) -> str:
    return f"{100 * s['mean']:.1f} ({100 * s['ci95'][0]:.1f}-{100 * s['ci95'][1]:.1f})"


def diff(c: dict) -> str:
    better, same, worse = c["better_same_worse"]
    return (f"{100 * c['mean_difference']:+.1f} | {100 * c['ci95'][0]:+.1f} to {100 * c['ci95'][1]:+.1f} | "
            f"{better} / {same} / {worse} | {c['p_sign_flip']:.4f} | {c['p_wilcoxon']:.4f}")


def render(results: dict) -> str:
    lines = ["# Calibration-free spelling: full results", "",
             "Generated by `render_results.py` from `results/calibration_free_results.json`. Exact-letter accuracy in %, "
             "participant mean, with a 95% bootstrap interval over participants in brackets. Chance is 2.8%.", ""]
    for pipeline, block in results["pipelines"].items():
        label = "primary pipeline (`binned`)" if pipeline == "binned" else "UMM authors' preprocessing (`authors`)"
        lines += [f"## {label}", ""]
        pooled = block["all_als_participants"]
        lines += ["### All 19 people with ALS (both sites)", "",
                  "| Method | Mean (95% CI) | Worst participant |", "|---|---|---:|"]
        for method in ("transfer", "umm_memory", "seeded_umm"):
            lines.append(f"| {method} | {pct(pooled[method])} | {100 * pooled[method]['min']:.1f} |")
        lines += ["", "| Comparison | Difference (points) | 95% CI | Better / same / worse | p (exact sign-flip) | p (Wilcoxon) |",
                  "|---|---:|---|---|---:|---:|"]
        for name, c in pooled.items():
            if " - " in name:
                lines.append(f"| {name} | {diff(c)} |")
        lines.append("")
        for dataset, entry in block["datasets"].items():
            k = entry["calibration_letters"]
            lines += [f"### {TITLES[dataset]}", "",
                      f"| Method | All letters | Worst participant | First {k} letters | After letter {k} | Per participant, all letters |",
                      "|---|---|---:|---|---|---|"]
            for method, blocks in entry["methods"].items():
                if method == "supervised":
                    lines.append(f"| supervised ({k} labelled letters) | not usable for the first {k} | | | {pct(blocks['late'])} | |")
                    continue
                each = ", ".join(f"{100 * v:.0f}" for v in blocks["all"]["per_participant"])
                lines.append(f"| {method} | {pct(blocks['all'])} | {100 * blocks['all']['min']:.1f} | {pct(blocks['early'])} | "
                             f"{pct(blocks['late'])} | {each} |")
            lines += ["", "| Comparison | Difference (points) | 95% CI | Better / same / worse | p (exact sign-flip) | p (Wilcoxon) |",
                      "|---|---:|---|---|---:|---:|"]
            lines += [f"| {name} | {diff(c)} |" for name, c in entry["comparisons"].items()]
            if "by_sequences" in entry:
                methods = list(next(iter(entry["by_sequences"].values())))
                lines += ["", f"Accuracy after letter {k} by number of flash sequences per letter:", "",
                          "| Sequences | " + " | ".join(methods) + " |", "|---:|" + "---:|" * len(methods)]
                for sequences, row in entry["by_sequences"].items():
                    lines.append(f"| {sequences} | " + " | ".join(f"{100 * row[m]:.1f}" for m in methods) + " |")
            lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    results = json.loads((ROOT / "results" / "calibration_free_results.json").read_text(encoding="utf-8"))
    (ROOT / "RESULTS.md").write_text(render(results), encoding="utf-8")
    print("wrote RESULTS.md")
