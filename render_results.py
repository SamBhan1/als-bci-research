"""Render and validate the checked-in calibration-free analysis report."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).parent
TITLES = {"rome_als": "Rome, 8 people with ALS, row/column (BNCI 2014-008)",
          "rome_healthy": "Rome, 10 healthy people, row/column (BNCI 2014-009)",
          "etsu_als": "ETSU, 11 people with ALS, checkerboard (bigP3BCI Study L)"}
REQUIRED_PIPELINES = ("binned", "authors")
REQUIRED_DATASETS = ("rome_als", "rome_healthy", "etsu_als")


def validate_results(results: dict) -> None:
    """Validate the minimum schema needed by the renderer and prevent stale reports."""
    if results.get("schema_version") != 1:
        raise ValueError("unsupported or missing result schema_version")
    if not isinstance(results.get("pipelines"), dict):
        raise ValueError("results.pipelines must be an object")
    missing = [name for name in REQUIRED_PIPELINES if name not in results["pipelines"]]
    if missing:
        raise ValueError(f"results missing pipeline(s): {', '.join(missing)}")
    for pipeline in REQUIRED_PIPELINES:
        block = results["pipelines"][pipeline]
        if not isinstance(block.get("all_als_participants"), dict):
            raise ValueError(f"{pipeline}: missing all_als_participants")
        missing = [name for name in REQUIRED_DATASETS if name not in block.get("datasets", {})]
        if missing:
            raise ValueError(f"{pipeline}: missing dataset(s): {', '.join(missing)}")


def pct(s: dict) -> str:
    return f"{100 * s['mean']:.1f} ({100 * s['ci95'][0]:.1f}-{100 * s['ci95'][1]:.1f})"


def diff(c: dict) -> str:
    better, same, worse = c["better_same_worse"]
    return (f"{100 * c['mean_difference']:+.1f} | {100 * c['ci95'][0]:+.1f} to {100 * c['ci95'][1]:+.1f} | "
            f"{better} / {same} / {worse} | {c['p_sign_flip']:.4f} | {c['p_wilcoxon']:.4f}")


def render(results: dict) -> str:
    validate_results(results)
    chance = 100 * results.get("chance_accuracy", 1 / 36)
    lines = ["# Calibration-free spelling: full results", "",
             "Generated by `render_results.py` from `results/calibration_free_results.json`. Exact-letter accuracy in %, "
             f"participant mean, with a 95% bootstrap interval over participants in brackets. Chance is {chance:.1f}%.", ""]
    for pipeline, block in results["pipelines"].items():
        label = "primary pipeline (`binned`)" if pipeline == "binned" else "UMM authors' preprocessing (`authors`)"
        lines += [f"## {label}", ""]
        pooled = block["all_als_participants"]
        lines += ["### All 19 people with ALS (both sites)", "",
                  "| Method | Mean (95% CI) | Worst participant |", "|---|---|---:|"]
        for method in ("transfer", "umm_memory", "seeded_umm"):
            lines.append(f"| {method} | {pct(pooled[method])} | {100 * pooled[method]['min']:.1f} |")
        lines += ["", "| Comparison | Difference (points) | 95% CI | Better / same / worse | p (exact sign-flip) | p (Wilcoxon) |",
                  "|---|---:|---|---|---:|---:|"]
        for name, c in pooled.items():
            if " - " in name:
                lines.append(f"| {name} | {diff(c)} |")
        lines.append("")
        for dataset, entry in block["datasets"].items():
            k = entry["calibration_letters"]
            lines += [f"### {TITLES[dataset]}", "",
                      f"| Method | All letters | Worst participant | First {k} letters | After letter {k} | Per participant, all letters |",
                      "|---|---|---:|---|---|---|"]
            for method, blocks in entry["methods"].items():
                if method == "supervised":
                    lines.append(f"| supervised ({k} labelled letters) | not usable for the first {k} | | | {pct(blocks['late'])} | |")
                    continue
                each = ", ".join(f"{100 * v:.0f}" for v in blocks["all"]["per_participant"])
                lines.append(f"| {method} | {pct(blocks['all'])} | {100 * blocks['all']['min']:.1f} | {pct(blocks['early'])} | "
                             f"{pct(blocks['late'])} | {each} |")
            lines += ["", "| Comparison | Difference (points) | 95% CI | Better / same / worse | p (exact sign-flip) | p (Wilcoxon) |",
                      "|---|---:|---|---|---:|---:|"]
            lines += [f"| {name} | {diff(c)} |" for name, c in entry["comparisons"].items()]
            if "by_sequences" in entry:
                methods = list(next(iter(entry["by_sequences"].values())))
                lines += ["", f"Accuracy after letter {k} by number of flash sequences per letter:", "",
                          "| Sequences | " + " | ".join(methods) + " |", "|---:|" + "---:|" * len(methods)]
                for sequences, row in entry["by_sequences"].items():
                    lines.append(f"| {sequences} | " + " | ".join(f"{100 * row[m]:.1f}" for m in methods) + " |")
            lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "results" / "calibration_free_results.json")
    parser.add_argument("--output", type=Path, default=ROOT / "RESULTS.md")
    parser.add_argument("--check", action="store_true", help="fail if the output is not up to date")
    args = parser.parse_args()
    results = json.loads(args.input.read_text(encoding="utf-8"))
    rendered = render(results)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            print(f"{args.output} is stale; run render_results.py to regenerate it")
            return 1
        print(f"checked {args.output}")
        return 0
    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
